//! The central styles file and the machine-readable token manifest.
//!
//! Format choice: Tailwind v4 `@theme static` with ordinary CSS custom properties. The
//! generated project already runs Tailwind v4, `@theme` is the one place where its
//! namespaces (`--color-*`, `--spacing`, `--radius-*`, `--text-*`, ...) generate
//! utilities, and plain `var()` references work in any CSS file, including raw
//! `?inline` imports that bypass Tailwind. `static` keeps every variable even when no
//! utility class mentions it (Tailwind otherwise prunes unused theme variables, which
//! would break the `var()` references in rewritten component CSS). StyleX was not
//! chosen: it needs a compile step per component and cannot express the captured
//! cascade (selectors, layers, media) without hand-conversion.

use super::plan::{Origin, Token, TokenSet};
use super::value::Category;
use cssparser::ToCss;
use serde::Serialize;
use std::collections::{BTreeMap, BTreeSet};

fn section(category: Option<Category>) -> (&'static str, u8) {
    match category {
        Some(Category::Spacing) => ("Spacing", 0),
        Some(Category::Color) => ("Color", 1),
        Some(Category::FontFamily) => ("Typography: families", 2),
        Some(Category::FontSize) => ("Typography: sizes", 3),
        Some(Category::FontWeight) => ("Typography: weights", 4),
        Some(Category::LetterSpacing) => ("Typography: tracking", 5),
        Some(Category::LineHeight) => ("Typography: leading", 6),
        Some(Category::Radius) => ("Radius", 7),
        Some(Category::Shadow) => ("Shadow", 8),
        Some(Category::BorderWidth) => ("Border width", 9),
        Some(Category::Easing) => ("Motion: easing", 10),
        Some(Category::Duration) => ("Motion: duration", 11),
        Some(Category::ZIndex) => ("Stacking", 12),
        Some(Category::Breakpoint) => ("Breakpoints", 13),
        Some(Category::Opacity) | Some(Category::Size) => ("Other", 14),
        None => ("Other site variables", 15),
    }
}

/// `(section, name, value, comment)` rows for the theme block.
fn rows(set: &TokenSet) -> Vec<(u8, &'static str, String, String, Option<String>)> {
    let mut rows = Vec::new();
    let mut seen: BTreeSet<String> = BTreeSet::new();
    if let Some(scale) = &set.spacing
        && !set.hoisted.iter().any(|h| h.name == scale.name)
    {
        let (title, order) = section(Some(Category::Spacing));
        rows.push((
            order,
            title,
            scale.name.clone(),
            scale.value.clone(),
            Some(format!(
                "base unit; scale steps are calc(var(--spacing) * n); {} declarations on the scale",
                scale.members
            )),
        ));
        seen.insert(scale.name.clone());
    }
    for h in &set.hoisted {
        let (title, order) = section(h.category);
        let note = format!("site variable, {} reference(s)", h.references);
        rows.push((order, title, h.name.clone(), h.value.clone(), Some(note)));
        seen.insert(h.name.clone());
    }
    for t in &set.tokens {
        if t.origin == Origin::Site || seen.contains(&t.name) {
            continue;
        }
        let (title, order) = section(Some(t.category));
        rows.push((
            order,
            title,
            t.name.clone(),
            t.value.clone(),
            Some(format!("{} use(s), named by {}", t.uses, t.basis.label())),
        ));
        seen.insert(t.name.clone());
    }
    for b in &set.breakpoints {
        if seen.insert(b.name.clone()) {
            let (title, order) = section(Some(Category::Breakpoint));
            rows.push((
                order,
                title,
                b.name.clone(),
                format!("{}px", super::value::fmt_num(b.px)),
                Some(format!(
                    "{} media quer{}; media conditions cannot use var(), queries stay literal",
                    b.uses,
                    if b.uses == 1 { "y" } else { "ies" }
                )),
            ));
        }
    }
    rows
}

pub fn central_css(set: &TokenSet, sources: &[String]) -> String {
    let mut out = String::new();
    out.push_str("/*\n * Design tokens. The single source for values that were repeated across the captured\n * stylesheets. Generated by `mochi tokens`; see tokens.report.md for what was merged and what\n * stayed literal.\n *\n");
    for s in sources {
        out.push_str(&format!(" * source: {s}\n"));
    }
    out.push_str(" *\n * `@theme static` (Tailwind v4) keeps every variable even if no utility mentions it, so\n * the var() references in the component stylesheets always resolve.\n */\n@theme static {\n");
    let mut rows = rows(set);
    rows.sort_by(|a, b| {
        a.0.cmp(&b.0)
            .then_with(|| sort_key(&a.3).total_cmp(&sort_key(&b.3)))
            .then(a.2.cmp(&b.2))
    });
    let mut current: Option<&str> = None;
    for (_, title, name, value, note) in &rows {
        if current != Some(*title) {
            if current.is_some() {
                out.push('\n');
            }
            out.push_str(&format!("  /* {title} */\n"));
            current = Some(*title);
        }
        let name = cssparser::Token::Ident(name.clone().into()).to_css_string();
        match note {
            Some(note) => out.push_str(&format!("  {name}: {value}; /* {note} */\n")),
            None => out.push_str(&format!("  {name}: {value};\n")),
        }
    }
    out.push_str("}\n");
    out
}

/// Order lengths by magnitude inside a section; everything else sorts by name.
fn sort_key(value: &str) -> f64 {
    let trimmed = value.trim();
    // Units are normalized so 0.1s sorts after 80ms and 1rem after 12px.
    for (unit, scale) in [
        ("rem", 16.0),
        ("px", 1.0),
        ("em", 16.0),
        ("ms", 1.0),
        ("s", 1000.0),
    ] {
        if let Some(n) = trimmed.strip_suffix(unit)
            && let Ok(v) = n.parse::<f64>()
        {
            return v * scale;
        }
    }
    trimmed.parse().unwrap_or(f64::MAX)
}

#[derive(Debug, Serialize)]
pub struct ManifestValue {
    pub literal: String,
    pub normalized: String,
}

#[derive(Debug, Serialize)]
pub struct ManifestToken {
    pub name: String,
    pub category: Category,
    pub css_properties: Vec<String>,
    pub values: Vec<ManifestValue>,
    pub theme_key: String,
    pub tailwind: BTreeMap<String, String>,
    pub uses: usize,
    pub origin: Origin,
    pub basis: super::plan::Basis,
}

#[derive(Debug, Serialize)]
pub struct Manifest {
    pub schema_version: u32,
    pub central_file: String,
    pub tokens: Vec<ManifestToken>,
    pub spacing: Option<super::plan::SpacingScale>,
    pub unnamed: Vec<super::plan::Unnamed>,
    /// Every custom property the central file defines. After the rewrite these may appear in
    /// computed styles of elements that did not have them before (the file is site-wide).
    pub defined_properties: Vec<String>,
}

/// The Tailwind utility class that applies `token` to a CSS property, if one exists.
pub fn utility(token: &Token, property: &str) -> Option<String> {
    let n = |prefix: &str| token.name.strip_prefix(prefix).map(str::to_string);
    let class = match token.category {
        Category::Color => {
            let c = n("--color-")?;
            let prefix = match property {
                "color" | "-webkit-text-fill-color" => "text",
                p if p.starts_with("background") => "bg",
                p if p.starts_with("border") => "border",
                p if p.starts_with("outline") => "outline",
                "fill" => "fill",
                "stroke" => "stroke",
                "caret-color" => "caret",
                "accent-color" => "accent",
                "text-decoration-color" => "decoration",
                _ => return None,
            };
            format!("{prefix}-{c}")
        }
        Category::Radius => format!("rounded-{}", n("--radius-")?),
        Category::Shadow => format!("shadow-{}", n("--shadow-")?),
        Category::FontFamily => format!("font-{}", n("--font-")?),
        Category::FontSize => format!("text-{}", n("--text-")?),
        Category::FontWeight => format!("font-{}", n("--font-weight-")?),
        Category::LetterSpacing => format!("tracking-{}", n("--tracking-")?),
        Category::LineHeight => format!("leading-{}", n("--leading-")?),
        Category::Easing => format!("ease-{}", n("--ease-")?),
        Category::Duration => format!("duration-(--{})", token.name.trim_start_matches("--")),
        Category::ZIndex => format!("z-(--{})", token.name.trim_start_matches("--")),
        _ => return None,
    };
    Some(class)
}

impl TokenSet {
    /// Tailwind class for a computed `property: value` pair when the value is a token
    /// (for example `background-color`, `#0a0a0a` -> `bg-ink`). `None` leaves the value to
    /// an arbitrary-value class or an explicit gap in the caller's report.
    pub fn class_for(&self, property: &str, value: &str) -> Option<String> {
        utility(self.token_for(property, value)?, property)
    }
}

/// Names of every variable [`central_css`] writes.
pub fn defined_properties(set: &TokenSet) -> Vec<String> {
    let mut names: Vec<String> = rows(set).into_iter().map(|r| r.2).collect();
    names.sort();
    names.dedup();
    names
}

pub fn manifest(set: &TokenSet, central_file: &str) -> Manifest {
    let mut tokens = Vec::new();
    for t in &set.tokens {
        let mut tailwind = BTreeMap::new();
        for p in &t.properties {
            if let Some(c) = utility(t, p) {
                tailwind.insert(p.clone(), c);
            }
        }
        tokens.push(ManifestToken {
            name: t.name.clone(),
            category: t.category,
            css_properties: t.properties.clone(),
            values: t
                .merged_spellings
                .iter()
                .map(|s| ManifestValue {
                    literal: s.clone(),
                    normalized: t.key.clone(),
                })
                .collect(),
            theme_key: t.name.clone(),
            tailwind,
            uses: t.uses,
            origin: t.origin,
            basis: t.basis,
        });
    }
    Manifest {
        schema_version: 1,
        central_file: central_file.to_string(),
        tokens,
        spacing: set.spacing.clone(),
        unnamed: set.unnamed.clone(),
        defined_properties: defined_properties(set),
    }
}

#[cfg(test)]
mod tests {
    use super::super::css::parse_sheet;
    use super::super::inventory::Inventory;
    use super::super::plan::{Options, TokenSet};
    use super::super::value::Context;
    use super::*;

    #[test]
    fn central_file_is_one_static_theme_block_with_sections() {
        let sheet = parse_sheet(
            ":root { --color-ink: #111 } .a { color: var(--color-ink); padding: 16px; background-color: #fff } .b { background-color: #fff; padding: 8px }",
        );
        let ctx = Context { rem_px: Some(16.0) };
        let set = TokenSet::build(
            &Inventory::collect(&[&sheet], ctx),
            ctx,
            &Options::default(),
        );
        let css = central_css(&set, &["fixture".into()]);
        assert_eq!(css.matches("@theme static {").count(), 1);
        assert!(css.contains("--spacing: 4px;"), "{css}");
        assert!(css.contains("--color-ink: #111;"), "{css}");
        assert!(css.contains("--color-white: #fff;"), "{css}");
        assert!(css.find("/* Spacing */").unwrap() < css.find("/* Color */").unwrap());
        // The emitted file parses back as CSS with the theme block intact.
        let parsed = parse_sheet(&css);
        assert!(matches!(&parsed.nodes[0], super::super::css::Node::At(a) if a.name == "theme"));
    }

    #[test]
    fn manifest_maps_tokens_to_tailwind_utilities() {
        let sheet = parse_sheet(
            ".a { background-color: #fff; border-radius: 4px } .b { background-color: #fff; border-radius: 4px }",
        );
        let ctx = Context { rem_px: Some(16.0) };
        let set = TokenSet::build(
            &Inventory::collect(&[&sheet], ctx),
            ctx,
            &Options::default(),
        );
        let m = manifest(&set, "src/styles/tokens.css");
        let white = m.tokens.iter().find(|t| t.name == "--color-white").unwrap();
        assert_eq!(
            white.tailwind.get("background-color").map(String::as_str),
            Some("bg-white")
        );
        let radius = m
            .tokens
            .iter()
            .find(|t| t.category == Category::Radius)
            .unwrap();
        assert!(
            radius
                .tailwind
                .get("border-radius")
                .is_some_and(|c| c.starts_with("rounded-"))
        );
        assert_eq!(m.schema_version, 1);
        assert_eq!(
            set.class_for("background-color", "rgb(255 255 255)")
                .as_deref(),
            Some("bg-white")
        );
        assert_eq!(set.class_for("background-color", "#123456"), None);
    }
}
