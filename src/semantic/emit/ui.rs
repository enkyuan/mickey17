//! `components/ui/<primitive>.tsx`: the only files that import `@base-ui/react`.
//! Each part is a typed pass-through; styling is supplied by the compositions.
use crate::semantic::patterns::Primitive;

/// Names of single-component primitives (no parts) and their exported component.
fn single(p: Primitive) -> Option<(&'static str, &'static str)> {
    match p {
        Primitive::Toggle => Some(("Toggle", "Toggle")),
        Primitive::ToggleGroup => Some(("ToggleGroup", "ToggleGroup")),
        Primitive::RadioGroup => Some(("RadioGroup", "RadioGroup")),
        Primitive::Menubar => Some(("Menubar", "Menubar")),
        _ => None,
    }
}

pub fn namespace(p: Primitive) -> &'static str {
    match p {
        Primitive::AlertDialog => "AlertDialog",
        Primitive::NavigationMenu => "NavigationMenu",
        Primitive::RadioGroup => "RadioGroup",
        Primitive::ToggleGroup => "ToggleGroup",
        Primitive::Accordion => "Accordion",
        Primitive::Checkbox => "Checkbox",
        Primitive::Collapsible => "Collapsible",
        Primitive::Combobox => "Combobox",
        Primitive::Dialog => "Dialog",
        Primitive::Field => "Field",
        Primitive::Menu => "Menu",
        Primitive::Menubar => "Menubar",
        Primitive::Popover => "Popover",
        Primitive::Select => "Select",
        Primitive::Switch => "Switch",
        Primitive::Tabs => "Tabs",
        Primitive::Toggle => "Toggle",
        Primitive::Tooltip => "Tooltip",
        Primitive::Button => "Button",
    }
}

/// Exported wrapper name of a part: `Tabs` + `Root` -> `TabsRoot`; single components keep their name.
pub fn wrapper_name(p: Primitive, part: &str) -> String {
    match single(p) {
        Some((_, name)) if part.is_empty() => name.to_owned(),
        _ => format!("{}{}", namespace(p), part),
    }
}

/// `None` for primitives the template already ships (`Button`).
pub fn file(p: Primitive) -> Option<(String, String)> {
    if p == Primitive::Button {
        return None;
    }
    let ns = namespace(p);
    let mut out = format!(
        "// Generated by `mochi semantic`. The only place `{}` is imported; parts are typed\n// pass-throughs so compositions style them without touching the primitive.\nimport {{ {ns} as Primitive }} from '{}'\n",
        p.module(),
        p.module()
    );
    if let Some((_, name)) = single(p) {
        out.push_str(&format!(
            "\nexport function {name}(props: Primitive.Props) {{\n  return <Primitive {{...props}} />\n}}\n"
        ));
        return Some((format!("src/components/ui/{}.tsx", p.ui_file()), out));
    }
    for part in p.parts() {
        out.push_str(&format!(
            "\nexport function {name}(props: Primitive.{part}.Props) {{\n  return <Primitive.{part} {{...props}} />\n}}\n",
            name = wrapper_name(p, part)
        ));
    }
    Some((format!("src/components/ui/{}.tsx", p.ui_file()), out))
}

/// Every exported wrapper name, so no composition or repeated component reuses one.
pub fn is_wrapper_name(name: &str) -> bool {
    const ALL: &[Primitive] = &[
        Primitive::Accordion,
        Primitive::AlertDialog,
        Primitive::Checkbox,
        Primitive::Collapsible,
        Primitive::Combobox,
        Primitive::Dialog,
        Primitive::Field,
        Primitive::Menu,
        Primitive::Menubar,
        Primitive::NavigationMenu,
        Primitive::Popover,
        Primitive::RadioGroup,
        Primitive::Select,
        Primitive::Switch,
        Primitive::Tabs,
        Primitive::Toggle,
        Primitive::ToggleGroup,
        Primitive::Tooltip,
    ];
    ALL.iter().any(|p| {
        if single(*p).is_some() {
            wrapper_name(*p, "") == name
        } else {
            p.parts().iter().any(|part| wrapper_name(*p, part) == name)
        }
    })
}
